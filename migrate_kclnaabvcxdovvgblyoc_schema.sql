update evento_especial
set fecha_inicio = (fecha::text || 'T' || hora_entrada::text)::timestamp,
    fecha_fin    = (fecha::text || 'T' || hora_salida::text)::timestamp,
    direccion_evento = coalesce(direccion_evento, lugar)
where fecha_inicio is null;

alter table evento_especial alter column fecha_inicio set not null;
alter table evento_especial alter column fecha_fin set not null;

