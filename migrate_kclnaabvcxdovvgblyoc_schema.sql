alter table evento_especial add column if not exists escuela_id integer not null default 2;
alter table evento_especial add column if not exists fecha_inicio timestamp;
alter table evento_especial add column if not exists fecha_fin timestamp;
alter table evento_especial add column if not exists tiene_geocerca boolean not null default false;
alter table evento_especial add column if not exists geocerca_lat double precision;
alter table evento_especial add column if not exists geocerca_lng double precision;
alter table evento_especial add column if not exists geocerca_radio integer;
