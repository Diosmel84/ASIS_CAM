-- ===== usuarios (no existía en este proyecto) =====
-- Misma tabla y mismas políticas RLS "anon" abiertas que ya existen en
-- zyxcummfswlnaupvaqor (ver la advertencia de seguridad de
-- supabase_schema.sql: esta app no usa Supabase Auth, así que cualquiera
-- con la clave publishable puede leer/escribir esto si se deja así).
create table if not exists usuarios (
    id serial primary key,
    usuario text not null unique,
    password text not null,
    rol text not null default 'admin',
    email text,
    email_respaldo text,
    reset_token text,
    reset_token_expira timestamptz,
    updated_at timestamptz not null default now()
);

alter table usuarios enable row level security;

drop policy if exists "usuarios_select_anon" on usuarios;
create policy "usuarios_select_anon" on usuarios
    for select
    to anon
    using (true);

drop policy if exists "usuarios_insert_anon" on usuarios;
create policy "usuarios_insert_anon" on usuarios
    for insert
    to anon
    with check (true);

drop policy if exists "usuarios_update_anon" on usuarios;
create policy "usuarios_update_anon" on usuarios
    for update
    to anon
    using (true)
    with check (true);

