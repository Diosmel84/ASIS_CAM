-- Único por dni: es la clave que usa syncTeacherToDocenteTable() en
-- script.js para el upsert (onConflict:'dni').
do $$
begin
    alter table docentes add constraint docentes_dni_key unique (dni);
exception
    when duplicate_object then null;
end $$;

-- Los ids preservados (algunos son directamente el id de app_data.teachers,
-- valores grandes tipo Date.now()) se insertaron a mano, no por secuencia;
-- se limpia cualquier default viejo y se arma una identity nueva para los
-- docentes que se agreguen de acá en adelante sin pisar los ids existentes
-- (arranca en 500000, muy por debajo de los ids tipo Date.now() y muy por
-- encima de los ids chicos ya usados).
alter table docentes alter column id drop default;
do $$
begin
    alter table docentes alter column id add generated by default as identity (start with 500000);
exception
    when others then null; -- ya tiene identity de una corrida anterior
end $$;

-- ===== evento_especial: fecha/hora_entrada/hora_salida -> fecha_inicio/fecha_fin =====
